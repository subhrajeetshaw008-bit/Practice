#WAP to show different math functions

import math
a=16
print('The Original number is:',a)
print('The square root of the given number is:',math.sqrt(a))
print('The floor value of the given number is:',math.floor(a))
print('The ceiling value of the given number is:',math.ceil(a))
print('The absolute value of the given number is:',math.fabs(a))
print('The factorial of the given number is:',math.factorial(a))
print('The exponential value of the given number is:',math.exp(a))
print('The log value of the given number is:',math.log(a))