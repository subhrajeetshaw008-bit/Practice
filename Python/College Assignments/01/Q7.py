#WAP to show bitwise operations between two numbers

a=int(input('Enter the first number:'))
b=int(input('Enter the second number:'))
print('The numbers are',a,'and',b)
print('Bitwise AND of a and b is:',a&b)
print('Bitwise OR of a and b is:',a|b)
print('Bitwise XOR of a and b is:',a^b)
print('Bitwise NOT of a is:',~a)
print('Bitwise NOT of b is:',~b)
print('Bitwise left shift of the given two numbers are:',a<<b)
print('Bitwise right shift of the given two numbers are:',a>>b)
